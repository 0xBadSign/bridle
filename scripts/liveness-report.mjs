// Summarise the keeper cron's liveness log into docs/evidence/liveness.md.
//   node scripts/liveness-report.mjs <liveness.jsonl | https://raw.githubusercontent.com/<owner>/bridle/liveness/liveness.jsonl> [out.md]
import fs from "fs";

const src = process.argv[2];
const out = process.argv[3] || "docs/evidence/liveness.md";
if (!src) {
  console.error("usage: node scripts/liveness-report.mjs <path-or-url> [out.md]");
  process.exit(2);
}
const text = /^https?:\/\//.test(src) ? await (await fetch(src)).text() : fs.readFileSync(src, "utf8");
const recs = text.split("\n").filter((l) => l.trim()).flatMap((l) => { try { return [JSON.parse(l)]; } catch { return []; } });
const vaultRecs = recs.filter((r) => r.vault !== "watchdog");
const watchdog = recs.filter((r) => r.vault === "watchdog");

const pct = (xs, p) => (xs.length ? xs.slice().sort((a, b) => a - b)[Math.min(xs.length - 1, Math.ceil((p / 100) * xs.length) - 1)] : null);
const fmtS = (ms) => (ms === null ? "n/a" : `${(ms / 1000).toFixed(1)} s`);
const fmtN = (n) => (n === null || n === undefined ? "n/a" : n === Infinity ? "unlimited" : String(n));

function row(name, rs) {
  const ticks = new Set(rs.map((r) => r.tick)).size;
  const finished = rs.filter((r) => /^finished/.test(r.outcome)).length;
  const lat = rs.map((r) => r.attest_latency_ms).filter((x) => typeof x === "number");
  const errors = rs.filter((r) => r.outcome === "error").length;
  return `| ${name} | ${ticks} | ${rs.filter((r) => r.outcome !== "idle").length} | ${finished} | ${fmtS(pct(lat, 50))} | ${fmtS(pct(lat, 95))} | ${errors} |`;
}

const vaults = [...new Set(vaultRecs.map((r) => r.vault))].sort();
const ticksAll = [...new Set(vaultRecs.map((r) => r.tick))].sort();
const last = vaultRecs[vaultRecs.length - 1];
const lines = [
  "# Keeper liveness",
  "",
  "Generated by `scripts/liveness-report.mjs` from the cron keeper's log (`liveness.jsonl` on the `liveness` branch). Latency is the time the keeper's `settle` call took, from sending it to the MPC attestation being recorded in the vault.",
  "",
  `Window: ${ticksAll[0] || "n/a"} to ${ticksAll[ticksAll.length - 1] || "n/a"} (UTC).`,
  "",
  "| Vault | Ticks | Ticks with work | Operations finished | Attestation latency median | p95 | Errors |",
  "|---|---|---|---|---|---|---|",
  ...vaults.map((v) => row(v, vaultRecs.filter((r) => r.vault === v))),
  vaults.length > 1 ? row("all vaults", vaultRecs) : "",
  "",
  `Watchdog failures (allowance below floor or a vault error): ${watchdog.length}.`,
  "",
  last ? `Latest allowances: arena agent key ${fmtN(last.arena_agent_allowance_near)} NEAR; cron key for ${last.vault} ${fmtN(last.cron_key_allowance_near)} NEAR.` : "",
  "",
].filter((l, i, a) => !(l === "" && a[i - 1] === ""));
const failures = vaultRecs.filter((r) => r.outcome === "error").slice(-10);
if (failures.length) lines.push("Recent errors:", "", ...failures.map((r) => `- ${r.tick} ${r.vault}: ${String(r.error || "").replace(/\|/g, "/")}`), "");
fs.mkdirSync(out.replace(/[\/][^\/]*$/, "") || ".", { recursive: true });
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${recs.length} records)`);
